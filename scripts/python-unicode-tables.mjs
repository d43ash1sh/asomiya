// Regenerates src/python/unicode-tables.ts from the JavaScript engine's own Unicode data, so the
// Python translation splits text into letters exactly like Intl.Segmenter. Run with Node.
import { writeFileSync } from 'node:fs';

const segmenter = new Intl.Segmenter(undefined, { granularity: 'grapheme' });
const count = (s) => [...segmenter.segment(s)].length;

function ranges(test) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const hit = c <= 0x10ffff && !(c >= 0xd800 && c <= 0xdfff) && test(c, String.fromCodePoint(c));
    if (hit && start < 0) start = c;
    if (!hit && start >= 0) {
      out.push(
        start === c - 1 ? start.toString(16) : `${start.toString(16)}-${(c - 1).toString(16)}`,
      );
      start = -1;
    }
  }
  return out.join(' ');
}

const tables = {
  PICTOGRAPHIC: ranges((_, x) => /^\p{Extended_Pictographic}$/u.test(x)),
  EXTRA_EXTEND: ranges((_, x) => /^(?=\p{Grapheme_Extend})[^\p{Mn}\p{Me}]$/u.test(x)),
  PREPEND: ranges((_, x) => count('a' + x) === 2 && count(x + 'a') === 1),
  LINKER: ranges((_, x) => count('a' + x) === 1 && count('ক' + x + 'ক') === 1),
  CONSONANT: ranges((_, x) => count('a' + x) === 2 && count('ক্' + x) === 1 && count('ক' + x) === 2),
};

const body = Object.entries(tables)
  .map(([name, value]) => `  ${name}: '${value}',`)
  .join('\n');
writeFileSync(
  new URL('../src/python/unicode-tables.ts', import.meta.url),
  `// Generated by scripts/python-unicode-tables.mjs (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). Do not edit.\n` +
    `// Code point ranges (hex) used by the Python translation to split text into letters.\n\n` +
    `export const UNICODE_TABLES = {\n${body}\n} as const;\n`,
);
console.log('wrote src/python/unicode-tables.ts');
