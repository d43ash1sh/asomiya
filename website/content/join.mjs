/** A conservative test count for the page ("400+"). */
function countTests() {
  let n = 0;
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (name.endsWith('.test.ts')) {
        n +=
          readFileSync(path, 'utf8').match(/^\s*(?:it|test)(?:\.each\([^)]*\))?\(/gm)?.length ?? 0;
      }
    }
  };
  walk(join(ROOT, 'tests'));
  // Static counting misses tests generated by it.each (about a hundred), so this stays a floor:
  // the suite has had over 400 tests since 0.4.0.
  return Math.max(400, Math.floor(n / 100) * 100);
}

const ERROR_CODES = readFileSync(join(ROOT, 'docs/ERRORS.md'), 'utf8').match(
  /^### [LPR]\d{3}/gm,
).length;
const PROVISIONAL = readFileSync(join(ROOT, 'docs/KEYWORDS.md'), 'utf8')
  .split('\n')
  .map((line) => /^\| `([^`]+)`\s*\|\s*([^|]+?)\s*\|.*\|\s*provisional\s*\|$/.exec(line))
  .filter(Boolean)
  .map(([, word, meaning]) => ({
    word,
    meaning,
    roman: KEYWORD_GLOSSARY.find((k) => k.word === word)?.roman[0] ?? '',
  }));
const FACTS = {
  keywords: KEYWORD_GLOSSARY.length,
  errors: ERROR_CODES,
  tests: countTests(),
  os: 3,
};

/** Runs a sample at build time; the page shows exactly what the interpreter says. */
function run(source, lang, { expectError = false } = {}) {
  const result = runSource(source);
  if ((result.error !== null) !== expectError) {
    throw new Error(`join page sample ${expectError ? 'should fail' : 'failed'}:\n${source}`);
  }
  const error =
    result.error === null
      ? ''
      : formatDiagnostic(result.error.diagnostic, {
          lang,
          source,
          fileName: 'break-me.asom',
        }).split('\n')[0];
  return { output: result.output, error };
}

